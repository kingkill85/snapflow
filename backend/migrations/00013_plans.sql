-- +goose Up
-- Plans (step 2b): floorplans of a project version with their zones and
-- placed products. Tenant-owned like projects (D12/D167): every table carries
-- tenant_id through a composite key to its parent, so a project moved to
-- another tenant carries its plans along (ON UPDATE CASCADE down the chain
-- projects -> project_versions -> plans -> zones/placements).

-- Target of plans' (version_id, tenant_id) key.
ALTER TABLE project_versions ADD CONSTRAINT project_versions_id_tenant_key UNIQUE (id, tenant_id);

CREATE TABLE plans (
    id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id          uuid NOT NULL,
    version_id         uuid NOT NULL,
    -- 'board' arrives in phase 3.
    kind               text NOT NULL DEFAULT 'floorplan' CHECK (kind IN ('floorplan')),
    name               text NOT NULL CHECK (btrim(name) <> '' AND char_length(name) <= 100),
    position           integer NOT NULL,
    -- RESTRICT: files are kept while referenced (copies share them).
    image_file_id      uuid NOT NULL REFERENCES files (id),
    image_width        integer NOT NULL CHECK (image_width > 0),
    image_height       integer NOT NULL CHECK (image_height > 0),
    -- Metres per image pixel, from the editor's two-point calibration.
    scale              double precision CHECK (scale IS NULL OR (scale > 0 AND scale < 'Infinity'::float8)),
    -- Edit lock (one holder; live while lock_expires_at > now()).
    lock_user_id       uuid REFERENCES users (id) ON DELETE SET NULL,
    lock_expires_at    timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    -- The version of the content (zones, placements, scale), D37.
    content_updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (version_id, tenant_id) REFERENCES project_versions (id, tenant_id) ON DELETE CASCADE ON UPDATE CASCADE,
    UNIQUE (id, tenant_id)
);
CREATE UNIQUE INDEX plans_name_key ON plans (version_id, lower(name));
CREATE INDEX plans_version_idx ON plans (version_id, position);
CREATE INDEX plans_image_file_idx ON plans (image_file_id);
CREATE INDEX plans_lock_user_idx ON plans (lock_user_id);

-- Zone and placement ids are generated by the client (undo/redo and the
-- selection keep identity); they are unique per plan.
CREATE TABLE plan_zones (
    plan_id   uuid NOT NULL,
    id        uuid NOT NULL,
    tenant_id uuid NOT NULL,
    name      text NOT NULL CHECK (btrim(name) <> '' AND char_length(name) <= 100),
    color     text NOT NULL CHECK (color ~ '^#[0-9a-f]{6}$'),
    opacity   double precision NOT NULL CHECK (opacity >= 0 AND opacity <= 1),
    -- Polygon in image pixels: [[x, y], ...].
    points    jsonb NOT NULL CHECK (jsonb_typeof(points) = 'array'),
    position  integer NOT NULL,
    PRIMARY KEY (plan_id, id),
    FOREIGN KEY (plan_id, tenant_id) REFERENCES plans (id, tenant_id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE plan_placements (
    plan_id           uuid NOT NULL,
    id                uuid NOT NULL,
    tenant_id         uuid NOT NULL,
    -- NULL: the variant was deleted from the catalog; the placement stays,
    -- flagged (D59).
    variant_id        uuid REFERENCES product_variants (id) ON DELETE SET NULL,
    x                 double precision NOT NULL,
    y                 double precision NOT NULL,
    width             double precision NOT NULL CHECK (width > 0),
    height            double precision NOT NULL CHECK (height > 0),
    rotation          double precision NOT NULL CHECK (rotation >= 0 AND rotation < 360),
    label             text NOT NULL DEFAULT '' CHECK (char_length(label) <= 100),
    -- The customer already has it (D185).
    existing          boolean NOT NULL DEFAULT false,
    -- Chosen optional add-ons; required ones are implied.
    addon_variant_ids uuid[] NOT NULL DEFAULT '{}',
    instance_values   jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(instance_values) = 'object'),
    -- Computed by the backend on every save; no foreign key, since zones and
    -- placements are replaced together.
    zone_id           uuid,
    position          integer NOT NULL,
    PRIMARY KEY (plan_id, id),
    FOREIGN KEY (plan_id, tenant_id) REFERENCES plans (id, tenant_id) ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX plan_placements_variant_idx ON plan_placements (variant_id);

