package plans

import (
	"time"

	"github.com/google/uuid"

	"github.com/kingkill85/snapflow/backend/internal/features/capabilities"
	"github.com/kingkill85/snapflow/backend/internal/platform/attrschema"
)

// BoardCreate adds a board plan (step 3c).
type BoardCreate struct {
	Name               string           `json:"name" doc:"1-100 characters, unique in the version ignoring case"`
	EnclosureVariantID *uuid.UUID       `json:"enclosureVariantId,omitempty" doc:"An enclosure (catalog variant): its enclosureRows x enclosureTePerRow give the rows; rows sent are then ignored"`
	Rows               []BoardRowCreate `json:"rows,omitempty" maxItems:"50" doc:"Rows of DIN rail without an enclosure (or with one whose size is unknown)"`
}

// BoardRowCreate is a row of a new board.
type BoardRowCreate struct {
	CapacityTE float64 `json:"capacityTe" doc:"Above 0, at most 999.9, one decimal" example:"12"`
}

// BoardRowInput is a row of DIN rail as the editor sends it.
type BoardRowInput struct {
	ID         uuid.UUID `json:"id" doc:"Generated by the client; unique within the board, kept across saves and version copies"`
	CapacityTE float64   `json:"capacityTe" doc:"Above 0, at most 999.9, one decimal; with an enclosure of known size the enclosure's TE per row (the value sent is ignored)"`
}

// BoardRow is a row as stored, with the TE its modules use.
type BoardRow struct {
	ID         uuid.UUID `json:"id"`
	CapacityTE float64   `json:"capacityTe"`
	UsedTE     float64   `json:"usedTe" doc:"Sum of the widths of the row's modules (unknown width counts 1 TE)"`
}

// BoardModuleInput is a module on a row as the editor sends it.
type BoardModuleInput struct {
	ID              uuid.UUID         `json:"id" doc:"Generated by the client; unique within the board, kept across saves and version copies"`
	RowID           uuid.UUID         `json:"rowId" doc:"A row of the same content"`
	OffsetTE        float64           `json:"offsetTe" doc:"Distance from the row's start in TE, at least 0, one decimal"`
	VariantID       *uuid.UUID        `json:"variantId" nullable:"true" doc:"null only for a stored module whose variant was deleted from the catalog"`
	Label           string            `json:"label" doc:"At most 100 characters; empty for none"`
	Existing        bool              `json:"existing" doc:"The customer already has it: counts technically, never in BOM, prices or proposals"`
	AddonVariantIDs []uuid.UUID       `json:"addonVariantIds" doc:"Chosen optional add-ons, as for placements"`
	InstanceValues  attrschema.Values `json:"instanceValues" doc:"Values of the category's instanceAttributes"`
}

// BoardModule is a module as stored, with its width.
type BoardModule struct {
	BoardModuleInput
	WidthTE float64 `json:"widthTe" doc:"The variant's railWidthTe; 1 when unknown (warning module_width_unknown)"`
	// CatalogVariantID is the variant as last saved (D229); not in the API.
	CatalogVariantID *uuid.UUID `json:"-"`
}

// BoardContentInput replaces a board's content as a whole.
type BoardContentInput struct {
	ExpectedContentUpdatedAt time.Time          `json:"expectedContentUpdatedAt" doc:"contentUpdatedAt as last read; plan.stale otherwise"`
	EnclosureVariantID       *uuid.UUID         `json:"enclosureVariantId" nullable:"true" doc:"The enclosure (catalog variant); null for none (free rails). null keeps an enclosure whose variant was deleted from the catalog unless removeEnclosure is set (D375)"`
	EnclosureExisting        bool               `json:"enclosureExisting,omitempty" doc:"The customer already has the enclosure: never in the BOM"`
	RemoveEnclosure          bool               `json:"removeEnclosure,omitempty" doc:"Remove an enclosure whose variant was deleted from the catalog (with enclosureVariantId null)"`
	Rows                     []BoardRowInput    `json:"rows" doc:"In order (the array order is stored); at most 50. With an enclosure of known size the rows are fitted to it (D357)"`
	Modules                  []BoardModuleInput `json:"modules" doc:"In order (the array order is stored); at most 1000"`
}

// BoardWarningCode says what is wrong with a module or the enclosure.
// Warnings never block a save.
type BoardWarningCode string

const (
	WarnModuleWidthUnknown      BoardWarningCode = "module_width_unknown"
	WarnModuleMountingFloorplan BoardWarningCode = "module_mounting_floorplan"
	WarnRowOverflow             BoardWarningCode = "row_overflow"
	WarnEnclosureSizeUnknown    BoardWarningCode = "enclosure_size_unknown"
	WarnModuleOverlap           BoardWarningCode = "module_overlap"
)

// BoardWarning is one warning of a board: of a module (moduleId set) or of
// the enclosure (moduleId null). The availability codes are those of
// placements (D54).
type BoardWarning struct {
	ModuleID       *uuid.UUID       `json:"moduleId" nullable:"true" doc:"The module; null for a warning of the enclosure"`
	Code           BoardWarningCode `json:"code" enum:"module_width_unknown,module_mounting_floorplan,row_overflow,enclosure_size_unknown,module_overlap,variant_deleted,variant_inactive,product_inactive,category_inactive,product_type_inactive,product_type_not_in_project,required_addon_unavailable,addon_unavailable,addon_not_linked"`
	AddonVariantID *uuid.UUID       `json:"addonVariantId,omitempty" doc:"The add-on of an add-on warning"`
}

// BoardContent is everything on a board.
type BoardContent struct {
	PlanID             uuid.UUID     `json:"planId"`
	ContentUpdatedAt   time.Time     `json:"contentUpdatedAt" doc:"Send it back as expectedContentUpdatedAt"`
	EnclosureVariantID *uuid.UUID    `json:"enclosureVariantId" nullable:"true"`
	EnclosureExisting  bool          `json:"enclosureExisting" doc:"The customer already has the enclosure: never in the BOM"`
	EnclosureDeleted   bool          `json:"enclosureDeleted" doc:"The board has an enclosure whose variant was deleted from the catalog (warning variant_deleted; removeEnclosure removes it)"`
	RowsFromEnclosure  bool          `json:"rowsFromEnclosure" doc:"The enclosure gives rows and capacity (read-only in the editor)"`
	Rows               []BoardRow    `json:"rows" doc:"In order"`
	Modules            []BoardModule `json:"modules" doc:"In order"`
	CapacityTE         float64       `json:"capacityTe" doc:"Sum of the rows' capacity"`
	UsedTE             float64       `json:"usedTe" doc:"Sum of the modules' widths"`
	// Capabilities of every variant used (modules and enclosure), by id.
	Capabilities map[string]capabilities.Capabilities `json:"capabilities" doc:"Capability summary of every variant used (modules, enclosure), by variant id"`
	Warnings     []BoardWarning                       `json:"warnings"`
}
