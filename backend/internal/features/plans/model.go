package plans

import (
	"time"

	"github.com/google/uuid"

	"github.com/kingkill85/snapflow/backend/internal/platform/attrschema"
)

// Limits.
const (
	MaxNameLength  = 100
	MaxLabelLength = 100
	MaxZones       = 200
	MaxPlacements  = 2000
	MinZonePoints  = 3
	MaxZonePoints  = 200
	MaxAddons      = 100
	MaxNeeds       = 2000
	MaxNoteLength  = 500
	MaxNeedQty     = 100
	// LockTTL is how long a lock lives after its last heartbeat; the editor
	// renews it every 30 s.
	LockTTL = 2 * time.Minute
	// KindFloorplan is the only plan kind of phase 2 ("board" comes in
	// phase 3).
	KindFloorplan = "floorplan"
)

// PlanActions are what the caller may do with a plan.
type PlanActions struct {
	Update    bool `json:"update" doc:"Rename, replace the image, reorder, delete, edit the content (projects.write, project active)"`
	BreakLock bool `json:"breakLock" doc:"Take the edit lock from another user (projects.delete, project active)"`
}

// PlanLock is the live edit lock of a plan.
type PlanLock struct {
	UserID    uuid.UUID `json:"userId"`
	Name      string    `json:"name" doc:"The holder's full name, or their email if they have none"`
	ExpiresAt time.Time `json:"expiresAt" doc:"Without a renewal the lock ends then"`
	Mine      bool      `json:"mine" doc:"The caller holds the lock"`
}

// NullablePlanLock is a PlanLock that may be null (D243).
type NullablePlanLock struct {
	_ struct{} `nullable:"true"`
	PlanLock
}

// PlanImage is a plan's background image.
type PlanImage struct {
	URL    string `json:"url" doc:"Download path of the current image (changes when the image is replaced, so it may be cached forever; works also after the project moved to another tenant)" example:"/api/plans/3f2c…/images/9a1b…"`
	Width  int32  `json:"width" doc:"Natural pixels of the stored image; all coordinates are image pixels"`
	Height int32  `json:"height"`
}

// Plan is a plan of a project version, without its content.
type Plan struct {
	ID               uuid.UUID         `json:"id"`
	VersionID        uuid.UUID         `json:"versionId"`
	ProjectID        uuid.UUID         `json:"projectId"`
	Kind             string            `json:"kind" enum:"floorplan"`
	Name             string            `json:"name"`
	Position         int32             `json:"position" doc:"Order within the version, 1 first"`
	Image            PlanImage         `json:"image"`
	Scale            *float64          `json:"scale,omitempty" doc:"Metres per image pixel (calibration); absent when not calibrated"`
	ZoneCount        int64             `json:"zoneCount"`
	PlacementCount   int64             `json:"placementCount"`
	NeedCount        int64             `json:"needCount"`
	CreatedAt        time.Time         `json:"createdAt"`
	UpdatedAt        time.Time         `json:"updatedAt" doc:"Send it back as expectedUpdatedAt when renaming or replacing the image"`
	ContentUpdatedAt time.Time         `json:"contentUpdatedAt" doc:"The version of the content"`
	Lock             *NullablePlanLock `json:"lock" doc:"The live edit lock, null when nobody holds it"`
	Can              PlanActions       `json:"can"`
}

// PlanZone is a zone (room, area) of a plan: a polygon in image pixels.
type PlanZone struct {
	ID      uuid.UUID    `json:"id" doc:"Generated by the client; unique within the plan"`
	Name    string       `json:"name" doc:"1-100 characters"`
	Color   string       `json:"color" doc:"#rrggbb" example:"#4f7cff"`
	Opacity float64      `json:"opacity" doc:"0-1"`
	Points  [][2]float64 `json:"points" doc:"Polygon corners [x, y] in image pixels, 3-200 points, inside the image"`
}

// PlanPlacementInput is a placed product as the editor sends it.
type PlanPlacementInput struct {
	ID        uuid.UUID  `json:"id" doc:"Generated by the client; unique within the plan"`
	VariantID *uuid.UUID `json:"variantId" nullable:"true" doc:"null only for a stored placement whose variant was deleted from the catalog"`
	X         float64    `json:"x" doc:"Centre in image pixels, inside the image"`
	Y         float64    `json:"y"`
	Width     float64    `json:"width" doc:"Above 0, at most the image width; the box may overhang the edge"`
	Height    float64    `json:"height" doc:"Above 0, at most the image height"`
	Rotation  float64    `json:"rotation" doc:"Degrees clockwise; normalised to [0, 360)"`
	Label     string     `json:"label" doc:"At most 100 characters; empty for none"`
	Existing  bool       `json:"existing" doc:"The customer already has it: counts technically, never in BOM, prices or proposals"`
	// AddonVariantIDs are the chosen optional add-ons.
	AddonVariantIDs []uuid.UUID       `json:"addonVariantIds" doc:"Chosen optional add-ons (add-on links of the variant); required add-ons are implied and need not be sent"`
	InstanceValues  attrschema.Values `json:"instanceValues" doc:"Values of the category's instanceAttributes"`
}

// PlanPlacement is a placed product as stored, with its computed zone.
type PlanPlacement struct {
	PlanPlacementInput
	ZoneID *uuid.UUID `json:"zoneId" nullable:"true" doc:"The smallest zone containing the centre (computed on every save); null for none"`
	// CatalogVariantID is the variant as last saved, kept after a catalog
	// deletion (the BOM still finds its snapshot); not part of the API.
	CatalogVariantID *uuid.UUID `json:"-"`
}

// PlanWarningCode says what is wrong with a placement's catalog
// references. Warnings never block a save.
type PlanWarningCode string

const (
	WarnVariantDeleted           PlanWarningCode = "variant_deleted"
	WarnVariantInactive          PlanWarningCode = "variant_inactive"
	WarnProductInactive          PlanWarningCode = "product_inactive"
	WarnCategoryInactive         PlanWarningCode = "category_inactive"
	WarnProductTypeInactive      PlanWarningCode = "product_type_inactive"
	WarnProductTypeNotInProject  PlanWarningCode = "product_type_not_in_project"
	WarnRequiredAddonUnavailable PlanWarningCode = "required_addon_unavailable"
	WarnAddonUnavailable         PlanWarningCode = "addon_unavailable"
	WarnAddonNotLinked           PlanWarningCode = "addon_not_linked"
)

// PlanWarning is one warning of a placement.
type PlanWarning struct {
	PlacementID uuid.UUID       `json:"placementId"`
	Code        PlanWarningCode `json:"code" enum:"variant_deleted,variant_inactive,product_inactive,category_inactive,product_type_inactive,product_type_not_in_project,required_addon_unavailable,addon_unavailable,addon_not_linked"`
	// AddonVariantID names the add-on of an add-on warning.
	AddonVariantID *uuid.UUID `json:"addonVariantId,omitempty" doc:"The add-on of required_addon_unavailable, addon_unavailable and addon_not_linked"`
}

// PlanNeedInput is a need of a zone (D186) as the editor sends it: what the
// room needs (lights, blinds, sockets, ...), not a catalog product and never
// in the BOM. With a position it is a load symbol drawn on the plan. Kept
// apart from PlanNeed so that fields the backend adds to the output later
// (3d) never become required input (D342). Connections are not part of a
// need (D340).
type PlanNeedInput struct {
	ID             uuid.UUID  `json:"id" doc:"Generated by the client; unique within the plan, kept across saves and version copies"`
	ZoneID         *uuid.UUID `json:"zoneId" nullable:"true" doc:"Without a position: the zone (required, a zone of the same content). With a position: computed by the backend (the smallest zone containing it, null for none), the value sent is ignored"`
	FunctionTypeID uuid.UUID  `json:"functionTypeId" doc:"An active function type (an inactive one is kept on a stored or restored need with a warning)"`
	Quantity       int32      `json:"quantity" doc:"1-100; n means n separate loads"`
	PowerW         *string    `json:"powerW" nullable:"true" doc:"Power per unit in W, a decimal string 0-100000 with at most 2 decimals; null for unknown" example:"7.5"`
	LoadTypeID     *uuid.UUID `json:"loadTypeId" nullable:"true" doc:"One of the function type's allowed load types (any when it lists none); null for none"`
	Label          string     `json:"label" doc:"At most 100 characters; empty for none"`
	Note           string     `json:"note" doc:"At most 500 characters; empty for none"`
	X              *float64   `json:"x" nullable:"true" doc:"Load symbol position in image pixels (with y), inside the image; null for a need without symbol"`
	Y              *float64   `json:"y" nullable:"true"`
}

// PlanNeed is a need as stored.
type PlanNeed struct {
	ID             uuid.UUID  `json:"id" doc:"Generated by the client; unique within the plan, kept across saves and version copies"`
	ZoneID         *uuid.UUID `json:"zoneId" nullable:"true" doc:"The zone; for a load symbol the smallest zone containing it (computed on every save), null for none"`
	FunctionTypeID uuid.UUID  `json:"functionTypeId"`
	Quantity       int32      `json:"quantity" doc:"1-100; n means n separate loads"`
	PowerW         *string    `json:"powerW" nullable:"true" doc:"Power per unit in W, a decimal string with exactly 2 decimals; null for unknown" example:"7.50"`
	LoadTypeID     *uuid.UUID `json:"loadTypeId" nullable:"true" doc:"null for none"`
	Label          string     `json:"label"`
	Note           string     `json:"note"`
	X              *float64   `json:"x" nullable:"true" doc:"Load symbol position in image pixels (with y); null for a need without symbol"`
	Y              *float64   `json:"y" nullable:"true"`
}

// input is the need as it would be sent back unchanged.
func (n PlanNeed) input() PlanNeedInput {
	return PlanNeedInput(n)
}

// NeedWarningCode says what is wrong with a need. Warnings never block a
// save.
type NeedWarningCode string

const (
	WarnNeedFunctionTypeInactive NeedWarningCode = "need_function_type_inactive"
	WarnNeedOutsideZones         NeedWarningCode = "need_outside_zones"
	WarnNeedLoadTypeNotAllowed   NeedWarningCode = "need_load_type_not_allowed"
)

// NeedWarning is one warning of a need.
type NeedWarning struct {
	NeedID uuid.UUID       `json:"needId"`
	Code   NeedWarningCode `json:"code" enum:"need_function_type_inactive,need_outside_zones,need_load_type_not_allowed"`
}

// PlanContent is everything drawn on a plan.
type PlanContent struct {
	PlanID           uuid.UUID       `json:"planId"`
	ContentUpdatedAt time.Time       `json:"contentUpdatedAt" doc:"Send it back as expectedContentUpdatedAt"`
	Scale            *float64        `json:"scale" nullable:"true" doc:"Metres per image pixel; null when not calibrated"`
	Zones            []PlanZone      `json:"zones" doc:"In draw order"`
	Placements       []PlanPlacement `json:"placements" doc:"In draw order"`
	Needs            []PlanNeed      `json:"needs" doc:"In order (per zone in the order of this list)"`
	Warnings         []PlanWarning   `json:"warnings"`
	NeedWarnings     []NeedWarning   `json:"needWarnings"`
}

// PlanContentInput replaces a plan's content as a whole.
type PlanContentInput struct {
	ExpectedContentUpdatedAt time.Time            `json:"expectedContentUpdatedAt" doc:"contentUpdatedAt as last read; plan.stale otherwise"`
	Scale                    *float64             `json:"scale" nullable:"true" doc:"Metres per image pixel, above 0; null for none"`
	Zones                    []PlanZone           `json:"zones" doc:"In draw order (the array order is stored); at most 200"`
	Placements               []PlanPlacementInput `json:"placements" doc:"In draw order (the array order is stored); at most 2000"`
	Needs                    []PlanNeedInput      `json:"needs,omitempty" doc:"In order (the array order is stored); at most 2000. Left out (or null) keeps the stored needs (D294), dropping those of deleted zones"`
	RestoredNeedIDs          []uuid.UUID          `json:"restoredNeedIds,omitempty" doc:"Needs of this save that come back from content saved before (undo/redo in the editor): like a stored need they keep an inactive function type or load type (D343)"`
}
